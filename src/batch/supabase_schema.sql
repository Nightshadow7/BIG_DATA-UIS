ALTER TABLE public.alertas_activas ADD COLUMN IF NOT EXISTS pronostico_6h_mm DOUBLE PRECISION DEFAULT 0.0;
ALTER TABLE public.alertas_activas ADD COLUMN IF NOT EXISTS probabilidad_lluvia_pct INTEGER DEFAULT 0;
ALTER TABLE public.alertas_activas ADD COLUMN IF NOT EXISTS probabilidad_desbordamiento_pct INTEGER DEFAULT 0;
