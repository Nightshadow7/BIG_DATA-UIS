-- =============================================================================
-- ESQUEMA RELACIONAL, REALTIME Y POLITICAS DE SEGURIDAD (RLS) EN SUPABASE
-- Sistema Predictivo de Alerta Temprana y Resiliencia Hidroclimatica en Santander
-- =============================================================================

-- 1. Tabla de Capa Oro: Umbrales historicos calculados por Apache Spark
CREATE TABLE IF NOT EXISTS public.umbrales_estaciones (
    codigoestacion TEXT PRIMARY KEY,
    nombreestacion TEXT,
    departamento TEXT,
    municipio TEXT,
    zonahidrografica TEXT,
    latitud DOUBLE PRECISION,
    longitud DOUBLE PRECISION,
    total_lecturas BIGINT,
    precipitacion_media DOUBLE PRECISION,
    precipitacion_maxima DOUBLE PRECISION,
    umbral_alerta_naranja DOUBLE PRECISION, -- Percentil 90 (Vigilancia Predictiva)
    umbral_alerta_roja DOUBLE PRECISION,    -- Percentil 99 (Desbordamiento Critico)
    actualizado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabla Operativa: Alertas predictivas T+3h en tiempo real para el Centro de Mando Web
CREATE TABLE IF NOT EXISTS public.alertas_activas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zona_id TEXT NOT NULL,                  -- 'north', 'south', etc.
    codigoestacion TEXT REFERENCES public.umbrales_estaciones(codigoestacion),
    titulo_alerta TEXT NOT NULL,
    tipo_alerta TEXT NOT NULL,              -- 'ALERTA CRÍTICA' | 'VIGILANCIA' | 'ESCENARIO REVISADO'
    color_alerta TEXT NOT NULL,             -- 'red' | 'orange' | 'reviewed'
    cuenca_sector TEXT NOT NULL,
    descripcion TEXT NOT NULL,
    estado_prioridad TEXT NOT NULL,
    precipitacion_registrada DOUBLE PRECISION,
    revisado BOOLEAN DEFAULT FALSE,
    fecha_evento TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Habilitar publicacion Realtime para que el cliente React + Vite reciba cambios por WebSockets
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'alertas_activas'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.alertas_activas;
    END IF;
END
$$;

-- =============================================================================
-- 4. POLITICAS DE SEGURIDAD A NIVEL DE FILA (ROW LEVEL SECURITY - RLS)
-- =============================================================================

ALTER TABLE public.umbrales_estaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alertas_activas ENABLE ROW LEVEL SECURITY;

-- 4.1. Lectura publica de la Capa Oro para el Centro de Mando Web (rol anon y authenticated)
DROP POLICY IF EXISTS "Lectura publica de umbrales Capa Oro" ON public.umbrales_estaciones;
CREATE POLICY "Lectura publica de umbrales Capa Oro"
    ON public.umbrales_estaciones
    FOR SELECT
    TO anon, authenticated
    USING (true);

-- 4.2. Escritura exclusiva del pipeline PySpark (service_role) sobre la Capa Oro
DROP POLICY IF EXISTS "Actualizacion de Capa Oro por motor Batch" ON public.umbrales_estaciones;
CREATE POLICY "Actualizacion de Capa Oro por motor Batch"
    ON public.umbrales_estaciones
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

-- 4.3. Lectura publica de alertas predictivas en tiempo real
DROP POLICY IF EXISTS "Lectura publica de alertas activas" ON public.alertas_activas;
CREATE POLICY "Lectura publica de alertas activas"
    ON public.alertas_activas
    FOR SELECT
    TO anon, authenticated
    USING (true);

-- 4.4. Actualizacion operativa del protocolo UNGRD y proyeccion T+3h desde el Centro de Mando
DROP POLICY IF EXISTS "Actualizacion operativa de alertas activas" ON public.alertas_activas;
CREATE POLICY "Actualizacion operativa de alertas activas"
    ON public.alertas_activas
    FOR UPDATE
    TO anon, authenticated, service_role
    USING (true)
    WITH CHECK (true);

-- 4.5. Insercion de alertas predictivas por el consumidor de Kafka
DROP POLICY IF EXISTS "Insercion de alertas por motor Kafka" ON public.alertas_activas;
CREATE POLICY "Insercion de alertas por motor Kafka"
    ON public.alertas_activas
    FOR INSERT
    TO anon, authenticated, service_role
    WITH CHECK (true);