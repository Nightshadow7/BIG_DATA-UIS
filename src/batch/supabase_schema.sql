-- 3. Habilitar publicacion Realtime para que el cliente React + Vite reciba cambios por WebSockets
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'alertas_activas'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.alertas_activas;
    END IF;
END
$$;

-- =============================================================================
-- 4. POLITICAS DE SEGURIDAD A NIVEL DE FILA (ROW LEVEL SECURITY - RLS)
-- =============================================================================

ALTER TABLE public.umbrales_estaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alertas_activas ENABLE ROW LEVEL SECURITY;

-- 4.1. Lectura publica de la Capa Oro para el Centro de Mando Web (rol anon y authenticated)
DROP POLICY IF EXISTS "Lectura publica de umbrales Capa Oro" ON public.umbrales_estaciones;
CREATE POLICY "Lectura publica de umbrales Capa Oro"
    ON public.umbrales_estaciones
    FOR SELECT
    TO anon, authenticated
    USING (true);

-- 4.2. Escritura exclusiva del pipeline PySpark (service_role) sobre la Capa Oro
DROP POLICY IF EXISTS "Actualizacion de Capa Oro por motor Batch" ON public.umbrales_estaciones;
CREATE POLICY "Actualizacion de Capa Oro por motor Batch"
    ON public.umbrales_estaciones
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

-- 4.3. Lectura publica de alertas predictivas en tiempo real
DROP POLICY IF EXISTS "Lectura publica de alertas activas" ON public.alertas_activas;
CREATE POLICY "Lectura publica de alertas activas"
    ON public.alertas_activas
    FOR SELECT
    TO anon, authenticated
    USING (true);

-- 4.4. Actualizacion operativa del protocolo UNGRD y proyeccion T+3h desde el Centro de Mando
DROP POLICY IF EXISTS "Actualizacion operativa de alertas activas" ON public.alertas_activas;
CREATE POLICY "Actualizacion operativa de alertas activas"
    ON public.alertas_activas
    FOR UPDATE
    TO anon, authenticated, service_role
    USING (true)
    WITH CHECK (true);

-- 4.5. Insercion de alertas predictivas por el consumidor de Kafka
DROP POLICY IF EXISTS "Insercion de alertas por motor Kafka" ON public.alertas_activas;
CREATE POLICY "Insercion de alertas por motor Kafka"
    ON public.alertas_activas
    FOR INSERT
    TO anon, authenticated, service_role
    WITH CHECK (true);