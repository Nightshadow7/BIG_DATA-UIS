-- 1. Tabla de Capa Oro: Parametros hidrologicos, estacionales y umbrales 3h entrenados en Apache Spark
CREATE TABLE IF NOT EXISTS public.umbrales_estaciones (
    codigoestacion TEXT PRIMARY KEY,
    nombreestacion TEXT,
    departamento TEXT,
    municipio TEXT,
    zonahidrografica TEXT,
    latitud DOUBLE PRECISION,
    longitud DOUBLE PRECISION,
    altitud_msnm DOUBLE PRECISION DEFAULT 950.0,
    total_lecturas BIGINT,
    precipitacion_media DOUBLE PRECISION,
    precipitacion_maxima DOUBLE PRECISION,
    desviacion_estandar DOUBLE PRECISION DEFAULT 0.0,
    media_epoca_lluvias_mm DOUBLE PRECISION DEFAULT 0.0,
    media_epoca_seca_mm DOUBLE PRECISION DEFAULT 0.0,
    factor_estacional_bimodal DOUBLE PRECISION DEFAULT 1.0,
    umbral_3h_p90 DOUBLE PRECISION,             -- Percentil 90 acumulado en ventana de 10.800 s (3h)
    umbral_3h_p99 DOUBLE PRECISION,             -- Percentil 99 acumulado en ventana de 10.800 s (3h)
    api_critico_24h_mm DOUBLE PRECISION,        -- Indice de Precipitacion Antecedente 24h (86.400 s)
    api_critico_72h_mm DOUBLE PRECISION,        -- Indice de Precipitacion Antecedente 72h (259.200 s)
    umbral_alerta_naranja DOUBLE PRECISION,     -- Alias compatible P90 3h (Vigilancia Predictiva)
    umbral_alerta_roja DOUBLE PRECISION,        -- Alias compatible P99 3h (Desbordamiento Critico)
    prob_transicion_exceso DOUBLE PRECISION,    -- Probabilidad condicional de Markov P(Exceso_t+3h | Sat_t)
    coef_escorrentia DOUBLE PRECISION,          -- Coeficiente de escorrentia orografica C_esc
    ventana_evacuacion_min INTEGER DEFAULT 150, -- Tiempo preventivo estimado antes del pico (min)
    actualizado_en TIMESTAMPTZ DEFAULT NOW()
);

-- Migraciones idempotentes para bases de datos existentes
ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS altitud_msnm DOUBLE PRECISION DEFAULT 950.0;
ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS desviacion_estandar DOUBLE PRECISION DEFAULT 0.0;
ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS media_epoca_lluvias_mm DOUBLE PRECISION DEFAULT 0.0;
ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS media_epoca_seca_mm DOUBLE PRECISION DEFAULT 0.0;
ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS factor_estacional_bimodal DOUBLE PRECISION DEFAULT 1.0;
ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS umbral_3h_p90 DOUBLE PRECISION;
ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS umbral_3h_p99 DOUBLE PRECISION;
