ALTER TABLE public.umbrales_estaciones ADD COLUMN IF NOT EXISTS ventana_evacuacion_min INTEGER DEFAULT 150;

-- 2. Tabla Operativa: Alertas predictivas multi-estacion (T+1h, T+3h, T+6h) en tiempo real
CREATE TABLE IF NOT EXISTS public.alertas_activas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zona_id TEXT NOT NULL,                              -- Identificador real de cuenca y municipio (sin limitar a 2 zonas)
    codigoestacion TEXT REFERENCES public.umbrales_estaciones(codigoestacion),
    nombreestacion TEXT,
    municipio TEXT,
    latitud DOUBLE PRECISION,
    longitud DOUBLE PRECISION,
    titulo_alerta TEXT NOT NULL,
    tipo_alerta TEXT NOT NULL,                          -- 'ALERTA CRÍTICA' | 'VIGILANCIA' | 'ESCENARIO REVISADO'
    color_alerta TEXT NOT NULL,                         -- 'red' | 'orange' | 'reviewed'
    cuenca_sector TEXT NOT NULL,
    descripcion TEXT NOT NULL,
    estado_prioridad TEXT NOT NULL,
    lluvia_actual_mm DOUBLE PRECISION DEFAULT 0.0,      -- Precipitacion observada en T0 (mm)
    pronostico_1h_mm DOUBLE PRECISION DEFAULT 0.0,      -- Volumen proyectado a T+1h (mm)
    pronostico_3h_mm DOUBLE PRECISION DEFAULT 0.0,      -- Volumen proyectado a T+3h (mm)
    pronostico_6h_mm DOUBLE PRECISION DEFAULT 0.0,      -- Volumen proyectado a T+6h (mm)
    probabilidad_lluvia_pct INTEGER DEFAULT 0,          -- Probabilidad satelital Open-Meteo (%)
    probabilidad_desbordamiento_pct INTEGER DEFAULT 0,  -- Probabilidad combinada Markov Spark + Open-Meteo (%)
    saturacion_suelo_pct DOUBLE PRECISION DEFAULT 45.0, -- Indice de saturacion antecedente del suelo (%)
    saturacion_antecedente_mm DOUBLE PRECISION DEFAULT 0.0,
    ventana_evacuacion_min INTEGER DEFAULT 150,
    precipitacion_registrada DOUBLE PRECISION,          -- Volumen acumulado de referencia T+3h (mm)
    revisado BOOLEAN DEFAULT FALSE,
    fecha_evento TIMESTAMPTZ DEFAULT NOW()
);

